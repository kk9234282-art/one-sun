import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const messages=[];
const context={self:{postMessage:message=>messages.push(message)},TextDecoder,Date,Number,Map,Set};
vm.createContext(context);
vm.runInContext(await readFile(new URL('../intelligence/static/csv-worker.js',import.meta.url),'utf8'),context);
const { CSVStream,normalize,fields,header }=context.self.AtlasCSV;
const rows=[];const parser=new CSVStream(row=>rows.push([...row]));
const fixture='\ufeffCIN,Company Name,Company Address\r\nU12345MH2010PTC000001,"Synthetic, test ""name""","first line\r\nsecond line"\r\n';
for(let i=0;i<fixture.length;i+=3)parser.feed(fixture.slice(i,i+3));
parser.feed('',true);
assert.deepEqual(rows,[['CIN','Company Name','Company Address'],['U12345MH2010PTC000001','Synthetic, test "name"','first line\r\nsecond line']]);
assert.throws(()=>new CSVStream(()=>{}).feed('a,"unclosed',true),/quoted field/);
assert.throws(()=>new CSVStream(()=>{}).feed('a,"closed"unexpected',true),/closing quote/);
const names=['CIN','Company Name','Company Class','Company Industrial Classification','Company Registration Date','Listing Status'].map(header);
const normalized=normalize(['U12345MH2010PTC000001','Synthetic fixture','One Person Company','Testing','29/02/2024','Unlisted'],names,'2026-10-31');
assert.equal(normalized[fields.indexOf('registered_class')],'One Person Company');
assert.equal(normalized[fields.indexOf('class')],'Private');
assert.equal(normalized[fields.indexOf('industry')],'Testing');
assert.equal(normalized[fields.indexOf('nic')],null);
assert.equal(normalized[fields.indexOf('incorporated')],'2024-02-29');
assert.throws(()=>normalize(['U1234PMH2010PTC000001','Bad fixture','Private','Testing','2010-01-01','Unlisted'],names,'2026-10-31'),/CIN/);
assert.throws(()=>normalize(['U12345MH2010PTC000001','Bad date','Private','Testing','2023-02-29','Unlisted'],names,'2026-10-31'),/calendar/);
const file=new File(['CIN,Company Name\nU12345MH2010PTC000001,Synthetic valid fixture\ninvalid,Synthetic rejected fixture\n'],'worker-test.csv');
await context.self.onmessage({data:{file,asOf:'2026-10-31'}});
const complete=messages.find(message=>message.type==='complete');
assert.equal(complete.accepted,1);assert.equal(complete.rejected,1);
assert.equal(messages.filter(message=>message.type==='batch').flatMap(message=>message.exceptions).length,1);
console.log('CSV worker tests passed: chunk boundaries, BOM, CRLF, quoted commas/newlines/quotes, validation, class/industry mapping and rejected records.');
